        Assert.Contains("public string? P { get; set; }", source);
        Assert.Contains("public string Q { get; set; }", source);
        Assert.Contains("public string? R { get; set; }", source);
        Assert.Contains("public object S { get; set; }", source);
        Assert.Contains("public long?[] T { get; set; }", source);
    }

    [Fact]
