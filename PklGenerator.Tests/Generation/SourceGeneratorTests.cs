        Assert.Contains("public Person? Owner { get; set; }", run.Sources["Zoo.PklGen_Dog.g.cs"]);
        Assert.Contains("public Dog[] Pets { get; set; } = default!;", run.Sources["Zoo.PklGen_Zoo.g.cs"]);
        AssertCompiles(run);
    }

    [Fact]
    public void MapsTheStandardLibraryTypesToCompilableCSharp()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Types.pkl", """
                                               a: String
                                               b: Boolean
                                               c: Int
                                               d: UInt8
                                               e: Float
                                               f: Duration
                                               g: DataSize
                                               h: Map<String, Int>
                                               i: Mapping<String, Listing<String>>
                                               j: Set<Int>
