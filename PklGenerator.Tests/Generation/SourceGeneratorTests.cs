    [Fact]
    public void PerFileNamespaceOverridesRootNamespace()
    {
        var run = GeneratorHost.Run(
            "Root",
            new PklTestFile("/proj/A.pkl", "x = 1", Namespace: "Custom.Ns"),
            new PklTestFile("/proj/B.pkl", "y = 1"));

        Assert.Contains("namespace Custom.Ns;", run.Sources["A.PklGen_A.g.cs"]);
        Assert.Contains("namespace Root;", run.Sources["B.PklGen_B.g.cs"]);
    }

    [Fact]
    public void FallsBackWhenNoNamespaceIsConfigured()
    {
        var run = GeneratorHost.Run(null, new PklTestFile("/proj/A.pkl", "x = 1"));

        Assert.Contains("namespace PklGenerated;", run.Sources["A.PklGen_A.g.cs"]);
    }

    [Fact]
    public void GeneratesClassesDeclaredInTheModule()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Zoo.pkl", """
                                             class Animal {
                                               name: String
