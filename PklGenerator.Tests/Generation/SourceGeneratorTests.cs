    [Fact]
    public void ComplexRealWorldModuleGenerates()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Server.pkl", """
                                                /// Server configuration
                                                @ModuleInfo { minPklVersion = "0.25.0" }
                                                module acme.Server

                                                import "pkl:json"

                                                typealias Environment = "dev"|"staging"|"prod"
                                                typealias Port = Int(isBetween(1, 65535))

                                                class Endpoint {
                                                  /// The path
                                                  path: String(startsWith("/"))
                                                  methods: Listing<"GET"|"POST"> = new { "GET" }
                                                  timeout: Duration = 30.s
                                                  limits: Mapping<String, DataSize>
                                                  function describe(): String = "\(path) (\(methods.length) methods)"
                                                }

                                                env: Environment = "dev"
                                                port: Port = 8080
                                                endpoints: Listing<Endpoint> = new {
                                                  new { path = "/health" }
                                                }
                                                local secret = read("env:SECRET")
                                                """));

        Assert.Empty(run.GeneratorDiagnostics);
        AssertCompiles(run);
        Assert.Contains("""public string Env { get; set; } = "dev";""", run.Sources["Server.PklGen_Server.g.cs"]);
        Assert.Contains("public long Port { get; set; } = 8080;", run.Sources["Server.PklGen_Server.g.cs"]);
        Assert.Contains("global::Pkl.PklTypes.Duration Timeout", run.Sources["Server.PklGen_Endpoint.g.cs"]);
    }

    private const string StatusSchema = """
        typealias Status = "active" | "in-progress" | "1st place"
        typealias Mode = ("fast" | "slow")?

        status: Status = "in-progress"
        other: Status
        maybe: Status?
        mode: Mode
        history: Listing<Status>
        labels: Mapping<Status, String>
        seen: Set<Status>
        plain: String = "in-progress"
        """;

    [Fact]
    public void StringUnionAliasesStayStringsUnlessEnumsAreEnabled()
    {
        var run = GeneratorHost.Run("Example", new PklTestFile("/proj/Jobs.pkl", StatusSchema));

        Assert.Empty(run.GeneratorDiagnostics);
        Assert.Equal(new[] { "Jobs.PklGen_Jobs.g.cs" }, run.Sources.Keys);
        Assert.Contains("public string Status { get; set; } = \"in-progress\";", run.Sources["Jobs.PklGen_Jobs.g.cs"]);
        AssertCompiles(run);
    }

    [Fact]
    public void StringUnionAliasesBecomeEnumsWhenEnabled()
    {
        var run = GeneratorHost.Run("Example", new PklTestFile("/proj/Jobs.pkl", StatusSchema, Enums: true));

        Assert.Empty(run.GeneratorDiagnostics);
        Assert.Equal(
            """
            // <auto-generated />
            #nullable enable
            namespace Example;

            [global::Pkl.PklStringUnion]
            public enum Status
            {
                [global::Pkl.PklStringUnionValue("active")]
                Active,
                [global::Pkl.PklStringUnionValue("in-progress")]
                InProgress,
                [global::Pkl.PklStringUnionValue("1st place")]
                _1stPlace,
            }

            """.Replace("\r\n", "\n"),
            Normalize(run.Sources["Jobs.PklGen_Status.g.cs"]));

        var jobs = run.Sources["Jobs.PklGen_Jobs.g.cs"];
        Assert.Contains("public Status Status { get; set; } = global::Example.Status.InProgress;", jobs);
        Assert.Contains("public Status Other { get; set; }", jobs);
        Assert.Contains("public Status? Maybe { get; set; }", jobs);
        Assert.Contains("public Mode? Mode { get; set; }", jobs);
        Assert.Contains("public Status[] History { get; set; } = default!;", jobs);
        Assert.Contains("global::System.Collections.Generic.Dictionary<Status, string> Labels", jobs);
        Assert.Contains("global::System.Collections.Generic.HashSet<Status> Seen", jobs);
        Assert.Contains("public string Plain { get; set; } = \"in-progress\";", jobs);
        AssertCompiles(run);
    }

    [Fact]
    public void OnlyAliasesOfStringLiteralsBecomeEnums()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Aliases.pkl", """
                                               typealias Pure = "a" | "b"
                                               typealias Mixed = "a" | Int
                                               typealias Open = "a" | String
                                               typealias Port = UInt16(this > 0)
                                               typealias Generic<T> = "a" | "b"

                                               pure: Pure
                                               mixed: Mixed
                                               wide: Open
                                               port: Port
                                               """, Enums: true));

        Assert.Equal(new[] { "Aliases.PklGen_Aliases.g.cs", "Aliases.PklGen_Pure.g.cs" }, run.Sources.Keys.OrderBy(k => k));
        var aliases = run.Sources["Aliases.PklGen_Aliases.g.cs"];
        Assert.Contains("public Pure Pure { get; set; }", aliases);
        Assert.Contains("public object Mixed { get; set; }", aliases);
        Assert.Contains("public string Wide { get; set; }", aliases);
        Assert.Contains("public ushort Port { get; set; }", aliases);
        AssertCompiles(run);
    }

    [Fact]
    public void EnumMemberNamesAreValidAndUnique()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Names.pkl", """
                                               typealias Odd = "a-b" | "a_b" | "A B" | "class" | "" | "-" | "9" | "snake_case_value" | "ünïcode"
                                               odd: Odd
                                               """, Enums: true));

        var source = Normalize(run.Sources["Names.PklGen_Odd.g.cs"]);
        foreach (var expected in new[] { "AB,", "AB_,", "AB__,", "Class,", "Empty,", "Value,", "_9,", "SnakeCaseValue,", "Ünïcode," })
        {
            Assert.Contains(expected, source);
        }

        Assert.Contains("[global::Pkl.PklStringUnionValue(\"a-b\")]\n    AB,", source);
        Assert.Contains("[global::Pkl.PklStringUnionValue(\"a_b\")]\n    AB_,", source);
        AssertCompiles(run);
    }

    [Fact]
    public void AnAliasCalledLikeTheModuleClassFallsBackToStringWithAWarning()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Status.pkl", "typealias Status = \"a\" | \"b\"\n\nstatus: Status", Enums: true));

        var warning = Assert.Single(run.GeneratorDiagnostics);
        Assert.Equal("PKLGEN004", warning.Id);
        Assert.Contains("'Status'", warning.GetMessage());
        Assert.Equal(new[] { "Status.PklGen_Status.g.cs" }, run.Sources.Keys);
        Assert.Contains("public string Status_ { get; set; }", run.Sources["Status.PklGen_Status.g.cs"]);
        AssertCompiles(run);
    }

    [Fact]
    public void EnumsAreOnlyGeneratedForTheFilesThatOptIn()
    {
        var schema = "typealias Level = \"low\" | \"high\"\n\nlevel: Level";
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/On.pkl", schema, Enums: true),
            new PklTestFile("/proj/Off.pkl", schema));

        Assert.Contains("On.PklGen_Level.g.cs", run.Sources.Keys);
        Assert.DoesNotContain("Off.PklGen_Level.g.cs", run.Sources.Keys);
    }
