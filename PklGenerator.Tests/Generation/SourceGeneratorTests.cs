using Microsoft.CodeAnalysis;

namespace PklGenerator.Tests.Generation;

public class SourceGeneratorTests
{
    private const string AppConfig = """
                                     import "NestedConfig.pkl"

                                     host: String = "127.0.0.1"

                                     typealias Port = UInt16(this > 0)
                                     port: Port = 5000

                                     nested: NestedConfig
                                     """;

    private const string NestedConfig = "title: String";

    private static void AssertCompiles(GeneratorRun run)
    {
        var problems = run.CompilationDiagnostics.Where(d => d.Severity >= DiagnosticSeverity.Warning).ToList();
        Assert.True(
            problems.Count == 0,
            "Generated code has compiler diagnostics:\n" + string.Join("\n", problems)
            + "\n\n" + string.Join("\n", run.Sources.Select(kv => $"// {kv.Key}\n{kv.Value}")));
    }

    private static string Normalize(string source) => source.Replace("\r\n", "\n");

    [Fact]
    public void GeneratesTheConsoleExampleSchema()
    {
        var run = GeneratorHost.Run(
            "Example",
            new PklTestFile("/proj/Schema/AppConfig.pkl", AppConfig),
            new PklTestFile("/proj/Schema/NestedConfig.pkl", NestedConfig));

        Assert.Empty(run.GeneratorDiagnostics);
        Assert.Equal(
            """
            // <auto-generated />
            #nullable enable
            namespace Example;

            public class AppConfig
            {
                public string Host { get; set; } = "127.0.0.1";
                public ushort Port { get; set; } = 5000;
                public NestedConfig Nested { get; set; } = default!;
            }

            """.Replace("\r\n", "\n"),
            Normalize(run.Sources["AppConfig.PklGen_AppConfig.g.cs"]));
        Assert.Contains("public string Title { get; set; } = default!;", run.Sources["NestedConfig.PklGen_NestedConfig.g.cs"]);
        AssertCompiles(run);
    }

    [Fact]
    public void FilesNotMarkedForGenerationAreIgnored()
    {
        var run = GeneratorHost.Run("Example", new PklTestFile("/proj/config.pkl", "x = 1", Generate: false));

