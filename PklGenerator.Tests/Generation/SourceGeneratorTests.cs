    [Fact]
    public void SyntaxErrorsAreReportedAtTheirLocation()
    {
        var run = GeneratorHost.Run("Example", new PklTestFile("/proj/Broken.pkl", "a = 1\nb = )\n"));

        Assert.Empty(run.Sources);
        var error = Assert.Single(run.GeneratorDiagnostics);
        Assert.Equal("PKLGEN003", error.Id);
        Assert.Equal(DiagnosticSeverity.Error, error.Severity);
        Assert.Equal("/proj/Broken.pkl", error.Location.GetLineSpan().Path);
        Assert.Equal(1, error.Location.GetLineSpan().StartLinePosition.Line);
        Assert.Equal(4, error.Location.GetLineSpan().StartLinePosition.Character);
    }

    [Fact]
    public void OneBrokenFileDoesNotStopOthersFromGenerating()
